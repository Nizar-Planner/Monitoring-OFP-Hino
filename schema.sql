-- 5. Konfigurasi Supabase Storage Bucket untuk Foto Bukti Part Failure (opf-attachments)
INSERT INTO storage.buckets (id, name, public) 
VALUES ('opf-attachments', 'opf-attachments', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Izinkan akses baca publik untuk foto bukti
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE schemaname = 'storage' AND tablename = 'objects' AND policyname = 'Public Access for opf-attachments'
  ) THEN
    CREATE POLICY "Public Access for opf-attachments" ON storage.objects FOR SELECT USING (bucket_id = 'opf-attachments');
  END IF;
END $$;

-- Izinkan upload file ke storage bucket opf-attachments
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE schemaname = 'storage' AND tablename = 'objects' AND policyname = 'Public Upload for opf-attachments'
  ) THEN
    CREATE POLICY "Public Upload for opf-attachments" ON storage.objects FOR INSERT WITH CHECK (bucket_id = 'opf-attachments');
  END IF;
END $$;
