-- 1. Tabel Utama Rekaman Klaim & Monitoring Part OPF (HMSI -> HMMI / HML)
CREATE TABLE IF NOT EXISTS public.opf_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dtr_number TEXT NOT NULL,
    part_name TEXT NOT NULL,
    part_number TEXT DEFAULT '',
    quantity INTEGER NOT NULL DEFAULT 1,
    model TEXT NOT NULL,
    chassis_number TEXT NOT NULL,
    engine_number TEXT NOT NULL,
    mileage INTEGER NOT NULL DEFAULT 0,
    dealer_name TEXT NOT NULL,
    qpi_number TEXT DEFAULT '',
    judgement_qpi TEXT DEFAULT '',
    judgement_date DATE DEFAULT NULL,
    request_date DATE NOT NULL DEFAULT CURRENT_DATE,
    tracking_status TEXT NOT NULL DEFAULT 'Waiting OFP',
    
    -- Verifikasi & Dokumentasi Tim Area HMSI
    area_received_date DATE DEFAULT NULL,
    area_received_by TEXT DEFAULT '',
    area_photo TEXT DEFAULT '',
    area_notes TEXT DEFAULT '',

    -- Verifikasi & Inspeksi Tim Quality HMSI
    quality_checked_date DATE DEFAULT NULL,
    quality_checked_by TEXT DEFAULT '',
    quality_photo TEXT DEFAULT '',
    quality_notes TEXT DEFAULT '',
    pos TEXT DEFAULT '', -- Lokasi penyimpanan gudang/rak Tim Quality (e.g. L2.1, L3.1)

    -- Pengiriman Fisik Part ke Pabrik HMMI / HML (Supplier)
    shipped_date DATE DEFAULT NULL,
    shipping_resi TEXT DEFAULT '',
    shipping_carrier TEXT DEFAULT '',

    -- Data Teknis Kerusakan & Penanda Tag OFP
    problem TEXT DEFAULT '', -- Deskripsi kerusakan / keluhan part
    occurred_date DATE DEFAULT NULL, -- Tanggal kejadian kerusakan unit
    repair_date DATE DEFAULT NULL, -- Tanggal perbaikan kendaraan

    -- Metrik Lead Time & SLA Overdue (> 30 Hari)
    days_elapsed INTEGER DEFAULT 0,
    is_overdue BOOLEAN DEFAULT FALSE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- Migrasi jika tabel sudah ada sebelumnya di Supabase
ALTER TABLE public.opf_records ADD COLUMN IF NOT EXISTS problem TEXT DEFAULT '';
ALTER TABLE public.opf_records ADD COLUMN IF NOT EXISTS pos TEXT DEFAULT '';
ALTER TABLE public.opf_records ADD COLUMN IF NOT EXISTS occurred_date DATE DEFAULT NULL;
ALTER TABLE public.opf_records ADD COLUMN IF NOT EXISTS repair_date DATE DEFAULT NULL;

-- 2. Unique Index untuk Mendukung Operasi UPSERT (Anti-Duplikasi TR/DTR & Part)
CREATE UNIQUE INDEX IF NOT EXISTS idx_opf_dtr_part_composite 
ON public.opf_records (dtr_number, part_name, part_number);

-- 3. Indeks Performa untuk Pencarian Cepat & Dashboard Analytics
CREATE INDEX IF NOT EXISTS idx_opf_tracking_status ON public.opf_records (tracking_status);
CREATE INDEX IF NOT EXISTS idx_opf_dealer_name ON public.opf_records (dealer_name);
CREATE INDEX IF NOT EXISTS idx_opf_request_date ON public.opf_records (request_date);
CREATE INDEX IF NOT EXISTS idx_opf_is_overdue ON public.opf_records (is_overdue);
CREATE INDEX IF NOT EXISTS idx_opf_dtr_number ON public.opf_records (dtr_number);

-- 4. Konfigurasi Row Level Security (RLS)
ALTER TABLE public.opf_records ENABLE ROW LEVEL SECURITY;

-- Izinkan Read / Select untuk semua pengguna (Anon & Authenticated)
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE tablename = 'opf_records' AND policyname = 'Public Read opf_records'
  ) THEN
    CREATE POLICY "Public Read opf_records" ON public.opf_records FOR SELECT USING (true);
  END IF;
END $$;

-- Izinkan Insert untuk semua pengguna (Anon & Authenticated)
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE tablename = 'opf_records' AND policyname = 'Public Insert opf_records'
  ) THEN
    CREATE POLICY "Public Insert opf_records" ON public.opf_records FOR INSERT WITH CHECK (true);
  END IF;
END $$;

-- Izinkan Update untuk semua pengguna (Anon & Authenticated)
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE tablename = 'opf_records' AND policyname = 'Public Update opf_records'
  ) THEN
    CREATE POLICY "Public Update opf_records" ON public.opf_records FOR UPDATE USING (true);
  END IF;
END $$;

-- Izinkan Delete untuk semua pengguna (Anon & Authenticated)
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies WHERE tablename = 'opf_records' AND policyname = 'Public Delete opf_records'
  ) THEN
